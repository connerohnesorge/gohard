package config

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"strconv"
	"strings"
)

// SchemaID is the $id of the JSON Schema.
const SchemaID = "https://raw.githubusercontent.com/connerohnesorge/" +
	"gohard/main/schema/gohard.schema.json"

// Patterns used by the schema. Tests check them against the Go
// validators on generated strings.
const (
	identPattern = `^[A-Za-z](_?[A-Za-z0-9])*$`
	unitPattern  = `^[A-Za-z](_?[A-Za-z0-9])*\.[A-Za-z](_?[A-Za-z0-9])*$`
	varPattern   = `^[^=\x00]+$`
	digitsRE     = `[0-9](_?[0-9])*`
)

// timePattern matches the syntax ParseTime accepts.
func timePattern() string {
	units := make([]string, len(timeUnits))
	for i, u := range timeUnits {
		units[len(units)-1-i] = anyCase(u.name)
	}
	return "^" + digitsRE + `(\.` + digitsRE + ")?([eE][+-]?" +
		digitsRE + ")? +(" + strings.Join(units, "|") + ")$"
}

// builtinPattern matches the built-in identifiers in any case.
func builtinPattern() string {
	alts := make([]string, len(Builtins))
	for i, b := range Builtins {
		alts[i] = anyCase(b)
	}
	return "^(" + strings.Join(alts, "|") + ")$"
}

func anyCase(s string) string {
	var b strings.Builder
	for _, r := range s {
		lo, up := strings.ToLower(string(r)), strings.ToUpper(string(r))
		if lo == up {
			b.WriteRune(r)
			continue
		}
		b.WriteString("[" + lo + up + "]")
	}
	return b.String()
}

// obj is a JSON object with a fixed key order.
type obj []kv

type kv struct {
	k string
	v any
}

// Schema returns schema/gohard.schema.json, the JSON Schema 2020-12 of
// gohard.yaml generated from the key table. `gohard config schema`
// prints it.
func Schema() []byte {
	root := obj{
		{"$schema", "https://json-schema.org/draft/2020-12/schema"},
		{"$id", SchemaID},
		{"title", "gohard.yaml"},
		{"description", "GoHard project configuration (#28). " +
			"Generated by tools/genconfig; do not edit."},
	}
	root = append(root, groupSchema("")...)
	var b bytes.Buffer
	writeJSON(&b, root, "")
	b.WriteByte('\n')
	return b.Bytes()
}

// groupSchema returns the object schema of the keys under prefix.
func groupSchema(prefix string) obj {
	var props obj
	var done []string
	for _, k := range keys {
		rest, ok := strings.CutPrefix(k.Name, prefix)
		if !ok {
			continue
		}
		head, _, nested := strings.Cut(rest, ".")
		if containsStr(done, head) {
			continue
		}
		done = append(done, head)
		if nested {
			g := prefix + head
			s := obj{{"description", GroupDoc(g)},
				{"type", []any{"object", "null"}}}
			props = append(props, kv{head,
				append(s, groupSchema(g + ".")[1:]...)})
			continue
		}
		props = append(props, kv{head, keySchema(k)})
	}
	return obj{
		{"type", "object"},
		{"additionalProperties", false},
		{"properties", props},
	}
}

func containsStr(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

func keySchema(k Key) obj {
	s := obj{{"description", k.Doc}}
	switch k.Type {
	case TypeBool:
		s = append(s, kv{"type", "boolean"})
	case TypeInt:
		s = append(s, kv{"type", "integer"}, kv{"minimum", k.Min},
			kv{"maximum", int64(math.MaxInt64)})
	case TypeUint64:
		s = append(s, kv{"type", "integer"}, kv{"minimum", 0},
			kv{"maximum", uint64(math.MaxUint64)})
	case TypeEnum:
		enum := make([]any, len(k.Enum))
		for i, e := range k.Enum {
			enum[i] = e
		}
		s = append(s, kv{"type", "string"}, kv{"enum", enum})
	case TypeTime:
		s = append(s, kv{"type", "string"},
			kv{"pattern", timePattern()})
	case TypeTimestamp:
		s = append(s, kv{"type", "string"}, kv{"format", "date-time"},
			kv{"pattern", "[Zz]$"})
	case TypeList:
		s = append(s, kv{"type", "array"}, kv{"items", itemSchema(k.Items)})
	case TypeMap:
		s = append(s, kv{"type", "object"},
			kv{"propertyNames", itemSchema(k.MapKeys)},
			kv{"additionalProperties", itemSchema(k.Items)})
	}
	return append(s, kv{"default", jsonDefault(k)})
}

func itemSchema(it Item) obj {
	switch it {
	case ItemNonEmpty:
		return obj{{"type", textTypes}, {"minLength", 1}}
	case ItemIdentifier:
		return obj{{"type", "string"}, {"pattern", identPattern}}
	case ItemDefine:
		return obj{{"type", "string"}, {"pattern", identPattern},
			{"not", obj{{"pattern", builtinPattern()}}}}
	case ItemUnit:
		return obj{{"type", "string"}, {"pattern", unitPattern}}
	case ItemVarName:
		return obj{{"type", "string"}, {"pattern", varPattern}}
	case ItemFolders:
		return obj{{"type", "array"}, {"items", itemSchema(ItemNonEmpty)}}
	}
	return obj{{"type", textTypes}}
}

// textTypes is the JSON type of a free string value: the loader takes an
// unquoted YAML number there as its text, so the schema must not flag it
// (only the YAML 1.1 bool spellings are rejected, which JSON Schema
// cannot tell from strings).
var textTypes = []any{"string", "number"}

// jsonDefault converts a key's YAML default to its JSON value.
func jsonDefault(k Key) any {
	switch k.Type {
	case TypeBool:
		return k.Default == "true"
	case TypeInt:
		n, _ := strconv.ParseInt(k.Default, 10, 64)
		return n
	case TypeUint64:
		n, _ := strconv.ParseUint(k.Default, 10, 64)
		return n
	case TypeList:
		return []any{}
	case TypeMap:
		return obj{}
	}
	if s, err := strconv.Unquote(k.Default); err == nil {
		return s
	}
	return k.Default
}

// writeJSON writes v indented by two spaces, keeping object key order.
func writeJSON(b *bytes.Buffer, v any, indent string) {
	inner := indent + "  "
	switch v := v.(type) {
	case obj:
		if len(v) == 0 {
			b.WriteString("{}")
			return
		}
		b.WriteString("{\n")
		for i, p := range v {
			b.WriteString(inner)
			writeString(b, p.k)
			b.WriteString(": ")
			writeJSON(b, p.v, inner)
			if i < len(v)-1 {
				b.WriteByte(',')
			}
			b.WriteByte('\n')
		}
		b.WriteString(indent + "}")
	case []any:
		if len(v) == 0 {
			b.WriteString("[]")
			return
		}
		b.WriteString("[")
		for i, e := range v {
			if i > 0 {
				b.WriteString(", ")
			}
			writeJSON(b, e, inner)
		}
		b.WriteString("]")
	case string:
		writeString(b, v)
	case bool:
		b.WriteString(strconv.FormatBool(v))
	case int:
		b.WriteString(strconv.Itoa(v))
	case int64:
		b.WriteString(strconv.FormatInt(v, 10))
	case uint64:
		b.WriteString(strconv.FormatUint(v, 10))
	default:
		panic(fmt.Sprintf("config: writeJSON: unexpected %T", v))
	}
}

func writeString(b *bytes.Buffer, s string) {
	var sb bytes.Buffer
	enc := json.NewEncoder(&sb)
	enc.SetEscapeHTML(false)
	enc.Encode(s)
	b.Write(bytes.TrimSuffix(sb.Bytes(), []byte("\n")))
}

// Markdown returns docs/config.md, the key reference generated from the
// key table.
func Markdown() []byte {
	var b bytes.Buffer
	b.WriteString(`# gohard.yaml

<!-- Generated by tools/genconfig from internal/config; do not edit. -->

GoHard reads its configuration from ` + "`gohard.yaml`" + ` at the
project root (#28). The project root is the nearest ancestor directory,
starting from the current directory (CLI) or the workspace folder
(language server), that contains ` + "`gohard.yaml`" + `; if none does, the
nearest ancestor containing ` + "`.git`" + `; if none does, the current
directory or workspace folder itself. A missing ` + "`gohard.yaml`" + `
means every key takes its default, with no diagnostic.

Every problem is reported with the line and column of the offending key
or value. ` + "`gohard config check`" + ` prints them; every other command
that loads an invalid configuration exits 2.

* Unknown keys and duplicate keys, at any nesting level, are errors.
  Keys of ` + "`libraries`, `defines` and `simulation.models`" + ` are VHDL
  names and compare case-insensitively.
* Bool keys accept only ` + "`true` and `false`" + `. Other YAML 1.1
  spellings (` + "`yes`, `no`, `on`, `off`, `y`, `n`, `True`, `FALSE`" + `
  and the like) are errors.
* An unquoted YAML 1.1 boolean spelling in a string value, such as
  ` + "`FOO: yes`" + ` under ` + "`defines`" + `, is an error; quote it.
  Any other unquoted scalar there (` + "`WIDTH: 8`, `X: 1.50`" + `) is
  taken as its exact text (` + "`\"8\"`, `\"1.50\"`" + `); the schema
  allows numbers in those places for that reason.
* ` + "`standard`" + ` must be a quoted string: ` + "`standard: \"2008\"`" + `.
* A key set to its default value gets the warning
  ` + "`config/redundant-default`" + ` (exit 1 only with ` + "`--strict`" + `).
* ` + "`--define NAME=VALUE`" + ` overrides the ` + "`defines:`" + ` entry with
  the same name, and logs the override to stderr.
* ` + "`gohard.yaml`" + ` wins over editor settings; the language server
  reports each overridden editor setting in a ` + "`window/logMessage`" + `.
* The JSON Schema is ` + "`schema/gohard.schema.json`" + `, also printed by
  ` + "`gohard config schema`" + `.

## Keys

| Key | Type | Default |
| --- | --- | --- |
`)
	for _, k := range keys {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | `%s` |\n", k.Name,
			anchor(k.Name), cell(k.TypeDoc), k.Default)
	}
	for _, k := range keys {
		fmt.Fprintf(&b, "\n### `%s`\n\n%s\n\n", k.Name, k.Doc)
		fmt.Fprintf(&b, "* Type: %s\n", k.TypeDoc)
		fmt.Fprintf(&b, "* Default: `%s`\n", k.Default)
	}
	return b.Bytes()
}

// anchor is the GitHub heading anchor of "### `name`".
func anchor(name string) string {
	return strings.ReplaceAll(name, ".", "")
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
