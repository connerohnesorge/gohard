package analyzer

import (
	"go/ast"
	"go/constant"
	"go/types"
	"regexp"
	"strconv"
	"strings"

	"golang.org/x/tools/go/analysis"
	"golang.org/x/tools/go/analysis/passes/inspect"
	"golang.org/x/tools/go/ast/inspector"
)

// Analyzer is the detlint analyzer.
var Analyzer = &analysis.Analyzer{
	Name:     "detlint",
	Doc:      "report ways around the env.Env doors in core packages",
	URL:      "https://github.com/connerohnesorge/gohard/issues/30",
	Requires: []*analysis.Analyzer{inspect.Analyzer},
	Run:      run,
}

func run(pass *analysis.Pass) (any, error) {
	ins := pass.ResultOf[inspect.Analyzer].(*inspector.Inspector)
	for file := range ins.Root().Children() {
		f, ok := file.Node().(*ast.File)
		if !ok {
			continue
		}
		name := pass.Fset.File(f.Pos()).Name()
		if !strings.HasSuffix(name, ".go") {
			continue // generated by the go command (test main, cgo)
		}
		test := strings.HasSuffix(name, "_test.go")
		rules := Rules(pass.Pkg.Path(), test)
		if rules == 0 {
			continue
		}
		c := &checker{pass: pass, rules: rules, test: test}
		c.linknames(f)
		c.file(file)
	}
	return nil, nil
}

type checker struct {
	pass  *analysis.Pass
	rules Rule
	test  bool
}

func (c *checker) report(n ast.Node, r Rule, what string) {
	if c.rules&r == 0 {
		return
	}
	c.pass.Report(analysis.Diagnostic{
		Pos:      n.Pos(),
		End:      n.End(),
		Category: r.String(),
		Message:  what + ": " + r.door(),
	})
}

func (c *checker) file(file inspector.Cursor) {
	kinds := []ast.Node{
		(*ast.ImportSpec)(nil),
		(*ast.Ident)(nil),
		(*ast.GoStmt)(nil),
		(*ast.SelectStmt)(nil),
		(*ast.RangeStmt)(nil),
		(*ast.CallExpr)(nil),
	}
	for cur := range file.Preorder(kinds...) {
		switch n := cur.Node().(type) {
		case *ast.ImportSpec:
			c.importSpec(n)
		case *ast.Ident:
			if !utcAfter(cur) {
				c.ident(n)
			}
			if c.rules&MapOrder != 0 {
				c.mapIterValue(cur, n)
			}
		case *ast.GoStmt:
			c.report(n, Go, "go statement")
		case *ast.SelectStmt:
			if !c.test || !poll(n) {
				c.report(n, Select, "select statement")
			}
		case *ast.RangeStmt:
			if c.rules&MapOrder != 0 {
				c.rangeStmt(cur, n)
			}
		case *ast.CallExpr:
			if c.rules&MapOrder != 0 {
				c.mapsIterCall(cur, n)
			}
			c.pointerVerb(n)
		}
	}
}

func (c *checker) importSpec(n *ast.ImportSpec) {
	path, err := strconv.Unquote(n.Path.Value)
	if err != nil {
		return
	}
	if b, ok := bannedImport(path); ok {
		c.report(n, b.rule, b.what)
	}
}

func (c *checker) ident(id *ast.Ident) {
	obj := c.pass.TypesInfo.Uses[id]
	if b, ok := obj.(*types.Builtin); ok {
		if r, ok := bannedBuiltins[b.Name()]; ok {
			c.report(id, r, "use of builtin "+b.Name())
		}
		return
	}
	if obj == nil || obj.Pkg() == nil {
		return
	}
	if fn, ok := obj.(*types.Func); ok {
		if m := methodName(fn); m != "" {
			if r, ok := bannedMethods[m]; ok {
				what := "call of " + m
				if r == MapOrder {
					what += ", which iterates in random order"
				}
				c.report(id, r, what)
			}
			return
		}
	}
	if obj.Parent() != obj.Pkg().Scope() {
		return // not package-level: fields, methods, locals
	}
	pkg, name := obj.Pkg().Path(), obj.Name()
	if pkg == c.pass.Pkg.Path() {
		return
	}
	what := pkg + "." + name
	if r, ok := bannedObjects[what]; ok {
		c.report(id, r, "use of "+what)
		return
	}
	switch obj.(type) {
	case *types.Func, *types.Var:
	default:
		return // types and constants touch nothing
	}
	switch pkg {
	case "os":
		if strings.HasPrefix(name, "Err") {
			return
		}
		if r, ok := osBan(name); ok {
			c.report(id, r, "use of "+what)
		}
	case "log":
		if _, fn := obj.(*types.Func); fn && logBan(name) {
			c.report(id, Stdio, "use of "+what)
		}
	}
}

// methodName returns "pkgpath.Type.Method" for a method of a named type
// and "" for anything else.
func methodName(fn *types.Func) string {
	sig, ok := fn.Type().(*types.Signature)
	if !ok || sig.Recv() == nil {
		return ""
	}
	t := sig.Recv().Type()
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	named, ok := types.Unalias(t).(*types.Named)
	if !ok || named.Obj().Pkg() == nil {
		return ""
	}
	return named.Obj().Pkg().Path() + "." + named.Obj().Name() + "." +
		fn.Name()
}

// linknames reports every //go:linkname directive in f: it binds to
// unexported runtime functions such as runtime.nanotime.
func (c *checker) linknames(f *ast.File) {
	for _, g := range f.Comments {
		for _, cm := range g.List {
			if strings.HasPrefix(cm.Text, "//go:linkname") {
				c.report(cm, Linkname, "//go:linkname directive")
			}
		}
	}
}

// utcAfter reports whether the identifier at cur is the function of a
// call converted straight to UTC, as in time.Unix(s, ns).UTC(): the
// zone is dropped before anything can read it.
func utcAfter(cur inspector.Cursor) bool {
	id := cur.Node().(*ast.Ident)
	switch id.Name {
	case "Unix", "UnixMilli", "UnixMicro":
	default:
		return false
	}
	var fun ast.Expr = id
	p := cur.Parent()
	if sel, ok := p.Node().(*ast.SelectorExpr); ok && sel.Sel == id {
		fun = sel
		p = p.Parent()
	}
	call, ok := p.Node().(*ast.CallExpr)
	if !ok || call.Fun != fun {
		return false
	}
	sel, ok := p.Parent().Node().(*ast.SelectorExpr)
	if !ok || sel.X != call || sel.Sel.Name != "UTC" {
		return false
	}
	_, ok = p.Parent().Parent().Node().(*ast.CallExpr)
	return ok
}

// printfFormat maps the fmt functions that take a format to the index
// of the format argument.
var printfFormat = map[string]int{
	"fmt.Sprintf": 0, "fmt.Errorf": 0, "fmt.Printf": 0,
	"fmt.Fprintf": 1, "fmt.Appendf": 1,
}

// pointerVerb reports a constant format with a %p verb: it prints a
// memory address.
func (c *checker) pointerVerb(call *ast.CallExpr) {
	i, ok := printfFormat[c.funcName(call)]
	if !ok || len(call.Args) <= i {
		return
	}
	tv := c.pass.TypesInfo.Types[call.Args[i]]
	if tv.Value == nil || tv.Value.Kind() != constant.String {
		return
	}
	if pointerVerbRE.MatchString(constant.StringVal(tv.Value)) {
		c.report(call.Args[i], Address, "%p verb")
	}
}

// pointerVerbRE matches a %p verb with any flags, width or precision,
// not counting %%.
var pointerVerbRE = regexp.MustCompile(`(^|[^%])(%%)*%[-+# 0]*` +
	`(\[\d+\])?(\d+|\*)?(\.(\d+|\*)?)?p`)

// poll reports whether s is a non-blocking poll of one channel: one
// communication clause plus default. It never blocks and never picks
// between ready cases at random.
func poll(s *ast.SelectStmt) bool {
	comm, def := 0, 0
	for _, cl := range s.Body.List {
		if cc, ok := cl.(*ast.CommClause); ok && cc.Comm == nil {
			def++
		} else {
			comm++
		}
	}
	return comm == 1 && def == 1
}
